export function buildTokenCssVariables(mode: 'dark' | 'light' = 'dark') {
  const theme = mode === 'light' ? ingradientThemeLight : ingradientThemeDark
  const palette = mode === 'light' ? foundationColorsLight : foundationColors
  const shadows = mode === 'light' ? shadowScaleLight : shadowScale
  return {
    ...staticVars,
    ...buildColorVars(theme, palette, shadows, mode === 'light'),
  }
}

// Backward-compat default export — dark mode css vars (existing callers).
export const tokenCssVariables = buildTokenCssVariables('dark')
